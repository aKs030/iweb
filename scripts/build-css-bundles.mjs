import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const checkOnly = globalThis.process.argv.includes("--check");

const bundles = [
  {
    output: "content/styles/core.bundle.css",
    sources: [
      "content/styles/foundation.css",
      "content/styles/main.css",
      "content/components/menu/styles/menu-base.css",
      "content/components/menu/styles/menu-states.css",
      "content/components/menu/styles/menu-mobile.css",
      "content/components/footer/footer.css",
    ],
  },
  {
    output: "content/styles/home.bundle.css",
    sources: [
      "content/components/interactions/interactions.css",
      "content/styles/pages/common.css",
      "content/styles/pages/home.css",
      "content/components/particles/three-earth.css",
      "content/components/typewriter/typewriter.css",
    ],
  },
];

async function renderBundle(bundle) {
  const sections = await Promise.all(
    bundle.sources.map(async source => {
      const css = await readFile(resolve(root, source), "utf8");
      return `/* source: /${source} */\n${css.trim()}`;
    })
  );

  const output = [
    "/* Generated by scripts/build-css-bundles.mjs. Edit the source files, not this bundle. */",
    ...sections,
    "",
  ].join("\n\n");
  return format(output, { parser: "css", printWidth: 100 });
}

const stale = [];

for (const bundle of bundles) {
  const outputPath = resolve(root, bundle.output);
  const expected = await renderBundle(bundle);

  if (checkOnly) {
    let current = "";
    try {
      current = await readFile(outputPath, "utf8");
    } catch {
      // A missing generated output is reported as stale below.
    }
    if (current !== expected) stale.push(bundle.output);
    continue;
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected);
  console.warn(`generated ${relative(root, outputPath)}`);
}

if (stale.length) {
  console.error(`CSS bundles are stale: ${stale.join(", ")}. Run npm run build:css.`);
  globalThis.process.exitCode = 1;
}
